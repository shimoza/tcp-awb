"""Generate COMMANDS.md and the three client hook files from the code (F1 step 12).

    python tools/gen_docs.py            print what is out of date and exit 1 when something is
    python tools/gen_docs.py --write    write the files

COMMANDS.md is docs/commands-guide.md (the hand-written text, edited there) followed by a reference of every
command and option taken from the argparse parsers: edit the help text of a parser, not the reference. The hook
files are `hooks.client_settings` with the prefix of their user: plugin/hooks/hooks.json (`awb hook`),
seal/work-claude/settings.json (with the deny list of the work user) and seal/work-claude/managed-settings.json.
tests/test_generated_docs.py checks that the committed files equal the generated ones.
"""
from __future__ import annotations

import argparse
import contextlib
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from awb import cli, hooks  # noqa: E402

GUIDE = ROOT / "docs" / "commands-guide.md"
COMMANDS = ROOT / "COMMANDS.md"
HOOK_FILES = {
    "plugin/hooks/hooks.json": ("awb hook", False),
    "seal/work-claude/settings.json": ("/usr/local/bin/awb hook", True),
    "seal/work-claude/managed-settings.json": ("/usr/local/bin/awb hook", False),
}
NOTICE = ("<!-- Generated by tools/gen_docs.py: edit docs/commands-guide.md or the help text of a parser, then run "
          "python tools/gen_docs.py --write. -->\n\n")
REFERENCE_HEAD = """
## Reference of every command and option

Taken from the parsers of the code. A command with a hand-written explanation above is described there in full;
this list is complete and cannot fall behind the code.
"""


class _Got(Exception):
    def __init__(self, parser):
        self.parser = parser


def _harvest(name: str, argv: list[str]) -> argparse.ArgumentParser | None:
    """The parser a command builds: parse_args is stopped at its first call and hands the parser over."""
    def stop(self, *a, **k):
        raise _Got(self)

    names = ("parse_args", "parse_known_args", "parse_intermixed_args")
    old = {n: getattr(argparse.ArgumentParser, n) for n in names}
    for n in names:
        setattr(argparse.ArgumentParser, n, stop)
    try:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            cli._delegate(name, argv + ["--help"])
    except _Got as got:
        return got.parser
    finally:
        for n, f in old.items():
            setattr(argparse.ArgumentParser, n, f)
    return None


def _parsers() -> list[tuple[str, str, argparse.ArgumentParser]]:
    found: list[tuple[str, str, argparse.ArgumentParser]] = []
    root = cli._build()
    for action in root._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {c.dest: _clean(c.help) for c in action._choices_actions}
            for name, sub in action.choices.items():
                if name not in cli.DELEGATED:
                    found.append((name, helps.get(name, ""), sub))
    for name in cli.DELEGATED:
        for extra in ([[]] if name != "kb" else [[], ["recheck-run"], ["recheck-watch"]]):
            parser = _harvest(name, extra)
            if parser is None:  # a command that reads its own arguments: the line of the root help only
                parser = argparse.ArgumentParser(prog="awb " + name, description=cli.DELEGATED[name][1], add_help=False)
            found.append((" ".join([name] + extra), cli.DELEGATED[name][1] if not extra else "", parser))
    return found


def _help(action, parser) -> str:
    text = " ".join((action.help or "").split())
    try:
        return text % {"default": action.default, "prog": parser.prog}
    except (TypeError, ValueError, KeyError):
        return text


def _positional(action) -> str:
    name = action.metavar if isinstance(action.metavar, str) else action.dest.upper()
    if action.nargs == "?":
        return "[%s]" % name
    if action.nargs == "*":
        return "[%s...]" % name
    if action.nargs == "+":
        return "%s..." % name
    return name


def _option(action) -> str:
    flags = "|".join(action.option_strings)
    if action.nargs == 0:
        return flags
    metavar = action.metavar if isinstance(action.metavar, str) else action.dest.upper()
    return "%s %s" % (flags, metavar)


def _clean(text: str | None) -> str:
    return " ".join((text or "").split())


def _walk(path: str, text: str, parser, out: list[str]) -> None:
    """One block per command that takes arguments or has no subcommand; the subcommands follow it."""
    visible = [a for a in parser._actions if a.help != argparse.SUPPRESS and not isinstance(a, argparse._HelpAction)]
    subs = [a for a in visible if isinstance(a, argparse._SubParsersAction)]
    positionals = [a for a in visible if not a.option_strings and a not in subs]
    options = [a for a in visible if a.option_strings]
    if positionals or options or not subs:
        usage = ["awb " + path] + [_positional(a) for a in positionals]
        usage += [("%s" if a.required else "[%s]") % _option(a) for a in options]
        out += ["", "### `%s`" % " ".join(usage)]
        if text:
            out += ["", text]
        for a in positionals + options:
            label = _option(a) if a.option_strings else _positional(a)
            note = _help(a, parser)
            if a.choices and not a.option_strings:
                note += (" " if note else "") + "(one of %s)" % ", ".join(map(str, a.choices))
            out.append("- `%s`%s" % (label, ": " + note if note else ""))
    for sub in subs:
        helps = {c.dest: _clean(c.help) for c in sub._choices_actions if c.help != argparse.SUPPRESS}
        for name, child in sub.choices.items():
            if name in helps or not sub._choices_actions:
                _walk(path + " " + name, helps.get(name, ""), child, out)


def commands_text() -> str:
    out: list[str] = []
    for path, text, parser in _parsers():
        _walk(path, text, parser, out)
    return NOTICE + GUIDE.read_text(encoding="utf-8").rstrip("\n") + "\n" + REFERENCE_HEAD + "\n".join(out).lstrip("\n").join(("\n", "\n"))


def hook_text(prefix: str, with_deny: bool) -> str:
    data = hooks.client_settings(prefix)
    if with_deny:
        data["permissions"] = {"deny": list(hooks.DENIED_TOOLS)}
    return json.dumps(data, indent=2) + "\n"


def generated() -> dict[Path, str]:
    files = {COMMANDS: commands_text()}
    for name, (prefix, deny) in HOOK_FILES.items():
        files[ROOT / name] = hook_text(prefix, deny)
    return files


def stale() -> list[Path]:
    return [p for p, text in generated().items() if not p.is_file() or p.read_text(encoding="utf-8") != text]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="gen_docs", description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true", help="write the files instead of checking them")
    args = ap.parse_args(argv)
    if args.write:
        for path, text in generated().items():
            path.write_text(text, encoding="utf-8")
            print("wrote %s" % path.relative_to(ROOT))
        return 0
    old = stale()
    for path in old:
        print("out of date: %s" % path.relative_to(ROOT))
    return 1 if old else 0


if __name__ == "__main__":
    sys.exit(main())
