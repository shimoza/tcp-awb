"""COMMANDS.md and the three client hook files are generated (tools/gen_docs.py): the committed files must equal them."""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

from awb import cli, hooks

ROOT = Path(__file__).resolve().parent.parent


def _gen():
    spec = importlib.util.spec_from_file_location("gen_docs", ROOT / "tools" / "gen_docs.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


GEN = _gen()
FILES = GEN.generated()


@pytest.mark.parametrize("path", sorted(FILES), ids=lambda p: p.relative_to(ROOT).as_posix())
def test_committed_file_equals_the_generated_one(path):
    assert path.read_text(encoding="utf-8") == FILES[path], "run: python tools/gen_docs.py --write"


def test_generator_check_finds_nothing_stale():
    assert GEN.stale() == []


def test_commands_reference_names_every_command():
    text = (ROOT / "COMMANDS.md").read_text(encoding="utf-8")
    assert text.startswith("<!-- Generated by tools/gen_docs.py")
    for name in cli.DELEGATED:
        assert "### `awb %s" % name in text, name
    for name in ("init", "intake", "register add", "spawn", "close", "projects list", "kb recheck-run"):
        assert "### `awb %s" % name in text, name


def test_hook_files_are_the_client_settings_and_the_work_user_denies_the_rest():
    for name, (prefix, deny) in GEN.HOOK_FILES.items():
        data = json.loads((ROOT / name).read_text(encoding="utf-8"))
        want = hooks.client_settings(prefix)
        if deny:
            want["permissions"] = {"deny": list(hooks.DENIED_TOOLS)}
        assert data == want, name
