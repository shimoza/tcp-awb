"""Build the table of the letters of other scripts that look like one Latin letter (finding 17 of the review of
2026-10-10), from the confusables data of Unicode Technical Standard #39.

The table is generated once and stored in the repository as awb/confusables_latin.py; the matcher reads only that
file, so nothing here runs at match time and nothing is downloaded then. To build it again from a newer data file:

    curl -o confusables.txt https://www.unicode.org/Public/security/latest/confusables.txt
    .venv/bin/python -m awb.confusables confusables.txt

What goes into the table, one line of the data file at a time:

- a source of one character that is not ASCII, a letter (a Unicode letter, or a letter by its name in the data file
  where the Python of the build does not know the character yet), no mark and no digit;
- whose target is one character that is a Latin letter or folds to one (the matcher's own fold of a small capital,
  a Latin alpha, a dotless i);
- and that the matcher does not already fold to plain letters (its hand-kept lists, the compatibility forms): the
  existing fold stays as it is, so the long s stays an s and a fullwidth I stays an I;
- a target l (the data file writes every vertical stroke as l) becomes I unless the source is a lower case letter,
  since a stroke in a name in capitals stands for an I.

Symbols and punctuation are left out on purpose: a box border or a danda that read as a letter would glue the name
next to it into a longer word.
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

TABLE_FILE = Path(__file__).resolve().parent / "confusables_latin.py"
_SKIP_WORDS = ("DIGIT", "NUMBER", "NUMERAL", "FRACTION")


def _chars(field: str) -> str:
    return "".join(chr(int(x, 16)) for x in field.split())


def _source_name(comment: str) -> str:
    """The name of the source character in the comment of a data line: `( s → t ) SOURCE NAME → TARGET NAME`."""
    _, _, rest = comment.partition(") ")
    return rest.partition(" → ")[0].strip()


def _is_letter(c: str, name: str) -> bool:
    cat = unicodedata.category(c)
    if cat.startswith("M") or unicodedata.digit(c, None) is not None:
        return False
    if any(w in name for w in _SKIP_WORDS):
        return False
    return cat.startswith("L") or (cat == "Cn" and "LETTER" in name)


def _one_latin(s: str) -> str | None:
    return s if len(s) == 1 and s.isascii() and s.isalpha() else None


def latin_table(data: str, fold=None) -> dict[str, str]:
    """{source: Latin letter} of the confusables data `data` by the rules of the module text. `fold` is the
    matcher's fold of one character without this table (matcher._fold_with with an empty table)."""
    if fold is None:
        from awb import matcher

        fold = lambda c: matcher._fold_with(c, {})   # noqa: E731
    out: dict[str, str] = {}
    for line in data.splitlines():
        body, _, comment = line.partition("#")
        fields = [f.strip() for f in body.split(";")]
        if len(fields) < 2 or not fields[0]:
            continue
        src, tgt = _chars(fields[0]), _chars(fields[1])
        if len(src) != 1 or src.isascii() or len(tgt) != 1:
            continue
        if not _is_letter(src, _source_name(comment)):
            continue
        done = fold(src)
        if done and done.isascii():
            continue   # the matcher folds it already: its own choice stays
        letter = _one_latin(tgt) or _one_latin(fold(tgt))
        if letter is None:
            continue
        if letter == "l" and unicodedata.category(src) != "Ll":
            letter = "I"
        out[src] = letter
    return out


def render(table: dict[str, str], version: str) -> str:
    lines = [
        '"""Letters of other scripts that look like one Latin letter, generated by awb/confusables.py from the',
        "confusables data of UTS #39 (%s)" % version,
        "with the Unicode %s data of Python." % unicodedata.unidata_version,
        'Do not edit by hand: build it again with `python -m awb.confusables confusables.txt`."""',
        "",
        "SOURCE = %r" % version,
        "",
        "LATIN = {",
    ]
    for c in sorted(table):
        lines.append('    "\\u%04x": "%s",' % (ord(c), table[c]) if ord(c) <= 0xFFFF else
                     '    "\\U%08x": "%s",' % (ord(c), table[c]))
    lines += ["}", ""]
    return "\n".join(lines)


def _version(data: str) -> str:
    version = date = ""
    for line in data.splitlines()[:20]:
        if line.startswith("# Version:"):
            version = line.split(":", 1)[1].strip()
        elif line.startswith("# Date:"):
            date = line.split(":", 1)[1].split(",")[0].strip()
    return "confusables.txt %s of %s" % (version or "?", date or "?")


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print("usage: python -m awb.confusables confusables.txt", file=sys.stderr)
        return 2
    data = Path(argv[0]).read_text(encoding="utf-8")
    table = latin_table(data)
    TABLE_FILE.write_text(render(table, _version(data)), encoding="utf-8")
    print("%d letters written to %s" % (len(table), TABLE_FILE.name))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
